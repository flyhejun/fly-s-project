/* ================================================================
 *  isqrt — 整数平方根
 *  二分查找，输入 32 位无符号整数，返回 16 位平方根。
 *  用于将 accel_sq 转换为 g 值，避免 float printf。
 * ================================================================ */
uint32_t isqrt(uint32_t n)
{
    uint32_t lo, hi, mid;

    if (n == 0) return 0;

    lo = 1;
    hi = 65535;

    while (lo <= hi)
    {
        mid = (lo + hi) / 2;
        if (mid * mid <= n) 
        {
            lo = mid + 1;
        }
        else                
        {
             hi = mid - 1;
        }
    }
    return hi;
}
